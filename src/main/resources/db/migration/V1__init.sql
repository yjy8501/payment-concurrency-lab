create table payment
(
    id         bigint generated by default as identity primary key,
    payment_no varchar(40) not null unique,
    amount     bigint      not null check (amount > 0),
    status     varchar(20) not null check (status in ('PENDING', 'APPROVED', 'FAILED', 'NEEDS_REVIEW')),
    -- 방식 ②(VersionedPayment)만 사용한다
    version    bigint      not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 방식 ④와 PG 승인 흐름이 쓰는 승인 기록. 결제당 최대 1건 (FR-004)
create table approval
(
    id          bigint generated by default as identity primary key,
    payment_id  bigint      not null references payment (id),
    pg_tx_id    varchar(40) not null,
    amount      bigint      not null,
    approved_at timestamptz not null,
    constraint uq_approval_payment unique (payment_id)
);

-- 방식 ①②③⑤가 쓰는 승인 기록. 중복이 몇 번 생기는지 세기 위해 유일 제약을 두지 않는다 (research R4)
create table approval_unguarded
(
    id          bigint generated by default as identity primary key,
    payment_id  bigint      not null references payment (id),
    pg_tx_id    varchar(40) not null,
    amount      bigint      not null,
    approved_at timestamptz not null
);

create index ix_approval_unguarded_payment on approval_unguarded (payment_id);
